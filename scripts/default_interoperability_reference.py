def run_cases(cases, rust, cpp):
    results = {}
    for name, case in cases:
        try:
            with tempfile.TemporaryDirectory(
                prefix=f"duckdb-default-interoperability-{name}-"
            ) as temp:
                results[name] = case(rust, cpp, Path(temp))
        except Exception as error:
            results[name] = {
                "passed": False,
                "error": {"type": type(error).__name__, "message": str(error)},
            }
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", choices=TARGETS, default="development")
    parser.add_argument("--duckdb", type=Path)
    parser.add_argument(
        "--rust", type=Path, default=ROOT / "target/release/duckdb-rust"
    )
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    if args.report.exists():
        raise FileExistsError("preserve prior evidence: choose a new report path")
    reference_path, identity = require_reference(args.duckdb, target=args.target)
    rust = Engine(args.rust.resolve(strict=True), True)
    cpp = Engine(
        reference_path,
        False,
        serialize_json_rows=TARGETS[args.target].serialize_json_rows,
    )
    report = {
        "recorded_at": datetime.now(timezone.utc).isoformat(),
        "reference_identity": identity,
        "script_sha256": digest(Path(__file__)),
        "rust_binary_sha256": digest(rust.binary),
        "cases": {},
        "full_parity": False,
        "scope": (
            "Bidirectional native checkpoint/WAL acceptance for representable "
            "built-in FUNCTION, CASE and predicate defaults, including deferred "
            "failure timing and continued writes by both engines."
        ),
    }
    report["cases"] = run_cases(
        [
            ("cpp_origin", cpp_origin),
            ("rust_checkpoint", rust_checkpoint),
            ("rust_wal", rust_wal),
            ("cpp_syntax_checkpoint", cpp_syntax_checkpoint),
            ("rust_syntax_checkpoint", rust_syntax_checkpoint),
            ("rust_syntax_wal", rust_syntax_wal),
        ],
        rust,
        cpp,
    )
    report["passed"] = all(
        case.get("passed") is True for case in report["cases"].values()
    )
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({"passed": report["passed"], "report": str(args.report)}))
    raise SystemExit(0 if report["passed"] else 1)


if __name__ == "__main__":
    main()
